#!/usr/bin/env python3
"""Generate security/psl_data.h from the Public Suffix List.

Usage: python3 scripts/gen-psl.py [psl.dat]
The generated C arrays are ASCII-only; Unicode rules are skipped because the
native URL parser does not perform IDNA conversion.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "security", "public_suffix_list.dat")
OUT = os.path.join(ROOT, "security", "psl_data.h")


def parse():
    normal, wildcard, exception = set(), set(), set()
    with open(SRC, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("//"):
                continue
            # Skip Unicode rules; the host parser is ASCII/punycode only.
            if any(ord(c) > 127 for c in line):
                continue
            if line.startswith("!"):
                exception.add(line[1:].lower())
            elif line.startswith("*."):
                wildcard.add(line[2:].lower())
            else:
                normal.add(line.lower())
    return sorted(normal), sorted(wildcard), sorted(exception)


def emit(name, values):
    out = ["static const char *const %s[] = {" % name]
    for v in values:
        out.append('    "%s",' % v.replace("\\", "\\\\").replace('"', '\\"'))
    out.append("};")
    out.append("static const size_t %s_count = sizeof(%s) / sizeof(%s[0]);" %
               (name, name, name))
    return "\n".join(out)


def main():
    normal, wildcard, exception = parse()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by scripts/gen-psl.py. Do not edit by hand.\n")
        f.write("// Source: Public Suffix List, MPL-2.0; see security/PSL-LICENSE.txt.\n")
        f.write("#ifndef WHISPER_PSL_DATA_H\n#define WHISPER_PSL_DATA_H\n\n")
        f.write("#include <stddef.h>\n\n")
        f.write(emit("w_psl_normal", normal) + "\n\n")
        f.write(emit("w_psl_wildcard", wildcard) + "\n\n")
        f.write(emit("w_psl_exception", exception) + "\n\n")
        f.write("#endif\n")
    print("gen-psl: %d normal, %d wildcard, %d exception -> %s" %
          (len(normal), len(wildcard), len(exception), OUT))


if __name__ == "__main__":
    main()
